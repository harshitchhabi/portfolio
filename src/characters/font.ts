/**
 * Lay out `text` starting at (x, y) top-left with capital height `size`.
 * Returns polylines in drawing coordinates. Unknown characters become spaces.
 */
export function letter(text: string, x: number, y: number, size: number, spacing = 1.45): Stroke[] {
  const k = size / 6;
  const out: Stroke[] = [];
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const glyph = G[ch];
    if (glyph) for (const s of glyph) out.push(s.map(([gx, gy]) => [cx + gx * k, y + gy * k]));
    cx += 4 * k * spacing;
  }
  return out;
}

/** Width of `text` set with letter(). */
export const textWidth = (text: string, size: number, spacing = 1.45) => (text.length * 4 * spacing - 4 * (spacing - 1)) * (size / 6);
